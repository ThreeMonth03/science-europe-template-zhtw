"""Opaque fixtures test preview boundaries, not PDF/Word rendering quality."""
import json
from pathlib import Path
import sys
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
import render_previews as preview
from artifact_utils import stage_candidate
from test_artifact_lifecycle import POCandidateFixture


class PreviewTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.native = self.root / 'native'
        self.native.mkdir()
        self.source = self.native / 'document.pdf'
        self.source.write_bytes(b'opaque preview unit fixture, not a PDF')
        self.receipt = {'kind': 'local-native-preview', 'render_passed': True, 'accepted': False,
                        'outputs': [{'path': 'document.pdf', 'sha256': preview.sha(self.source),
                                     'group': '435-en', 'kind': 'PDF'}]}
        self.save()
        self.args = SimpleNamespace(native=self.native, output=self.root / 'preview',
            pdftoppm=Path('/selected/pdftoppm'), pdfinfo=Path('/selected/pdfinfo'),
            soffice=Path('/selected/soffice'), docx_renderer=None, renderer_python=None)

    def save(self):
        (self.native / 'receipt.json').write_text(json.dumps(self.receipt))

    def fake_run(self, command, log, env=None):
        if '--convert-to' in command:
            folder = Path(command[command.index('--outdir') + 1])
            (folder / 'document.pdf').write_bytes(b'opaque LO preview fixture')
        else:
            Path(str(command[-1]) + '-1.png').write_bytes(b'opaque PNG fixture')

    def render(self):
        with patch.object(preview, 'run', side_effect=self.fake_run), \
             patch.object(preview.subprocess, 'check_output', return_value='Pages: 1\n'):
            return preview.render(self.args)

    def test_preview_preserves_native_and_never_accepts(self):
        original = preview.sha(self.source)
        report = self.render()
        self.assertEqual(original, preview.sha(self.source))
        self.assertTrue(report['render_passed'])
        self.assertFalse(report['accepted'])
        self.assertFalse(report['visual_review_complete'])
        self.assertFalse(report['microsoft_word_tested'])
        self.assertEqual('native-pdf', report['outputs'][0]['preview_route'])
        with self.assertRaises(FileExistsError):
            self.render()

    def test_word_preview_is_explicitly_not_native_pdf(self):
        self.receipt['outputs'][0]['kind'] = 'Word'
        self.save()
        self.assertEqual('libreoffice-docx-preview', self.render()['outputs'][0]['preview_route'])

    def test_canonical_renderer_uses_explicit_libreoffice(self):
        self.receipt['outputs'][0]['kind'] = 'Word'
        self.save()
        self.args.docx_renderer = Path('/selected/render_docx.py')
        self.args.renderer_python = Path('/selected/python')

        def fake(command, log, env=None):
            if command[1] == '-c':
                self.assertIn("m._resolve_soffice=lambda: '/selected/soffice'", command[2])
                self.assertEqual(str(self.args.renderer_python), str(command[0]))
                (log.parent / 'document.pdf').write_bytes(b'opaque canonical preview fixture')
                (log.parent / 'page-1.png').write_bytes(b'opaque canonical PNG fixture')
            else:
                self.fail('Canonical pages should not be regenerated by another renderer')

        with patch.object(preview, 'run', side_effect=fake), \
             patch.object(preview.subprocess, 'check_output', return_value='Pages: 1\n'):
            self.assertTrue(preview.render(self.args)['render_passed'])

    def test_tampered_or_external_native_is_rejected_before_output(self):
        for field, value in (('sha256', '0' * 64), ('path', '../outside.pdf'), ('path', str(self.source))):
            original = self.receipt['outputs'][0][field]
            self.receipt['outputs'][0][field] = value
            self.save()
            with self.subTest(field=field, value=value), self.assertRaises(ValueError):
                self.render()
            self.assertFalse(self.args.output.exists())
            self.receipt['outputs'][0][field] = original

    def test_incomplete_page_inventory_is_not_render_passed(self):
        with patch.object(preview, 'run', side_effect=self.fake_run), \
             patch.object(preview.subprocess, 'check_output', return_value='Pages: 2\n'), self.assertRaises(ValueError):
            preview.render(self.args)
        report = json.loads((self.args.output / 'preview-receipt.json').read_text())
        self.assertFalse(report['render_passed'])
        self.assertFalse(report['accepted'])


class PreviewIsNotAcceptanceTests(POCandidateFixture, unittest.TestCase):
    def test_preview_receipt_cannot_be_relabelled_as_pilot_report(self):
        self.report.update(kind='local-native-preview', render_passed=True, accepted=False)
        del self.report['passed']
        self.save()
        with self.assertRaises(ValueError):
            stage_candidate(self.build, self.root / 'store')
        self.assertFalse((self.root / 'store').exists())


if __name__ == '__main__':
    unittest.main()
